"""A rule a preset declines is an abstention in scoring (ADR-0015).

`rules_templates/rule-presets.json` is generated by build.rs from each rule's
`[presets]` block; bench reads it and never links the crate.
"""
import json
import unittest
from unittest import mock

from bench import rule_presets
from bench.db import BenchDB


class TestTable(unittest.TestCase):
    def test_every_rule_has_a_cell_per_preset_and_differs_is_derived(self):
        table = rule_presets.load()
        self.assertGreater(len(table), 300)
        cells = {"as_written", "narrowed", "widened", "stricter", "not_enforced"}
        for rule, row in table.items():
            for preset in rule_presets.PRESETS:
                self.assertIn(row[preset], cells, rule)
            self.assertEqual(
                row["differs"], len({row[p] for p in rule_presets.PRESETS}) > 1, rule)

    def test_strict_is_the_rule_as_written_or_declined(self):
        for rule, row in rule_presets.load().items():
            self.assertIn(row["strict"], ("as_written", "not_enforced"), rule)

    def test_the_file_is_what_the_generator_writes(self):
        # Sorted by rule id, one rule per line: the layout build.rs emits.
        text = rule_presets.TABLE_PATH.read_text()
        ids = list(json.loads(text)["rules"])
        self.assertEqual(ids, sorted(ids))

    def test_abstaining_rules_are_the_declined_ones(self):
        table = {"A-C": {"default": "narrowed", "strict": "as_written",
                         "pedantic": "not_enforced", "differs": True},
                 "B-C": {"default": "not_enforced", "strict": "not_enforced",
                         "pedantic": "not_enforced", "differs": False}}
        self.assertEqual(rule_presets.abstaining_rules("pedantic", table), {"A-C", "B-C"})
        self.assertEqual(rule_presets.abstaining_rules("strict", table), {"B-C"})
        with self.assertRaises(ValueError):
            rule_presets.abstaining_rules("relaxed", table)


class TestScoring(unittest.TestCase):
    def _score(self, preset):
        db = BenchDB.__new__(BenchDB)
        keys = {"p": {("a.c", 1, "A-C"), ("a.c", 2, "B-C"), ("a.c", 3, "B-C")}}
        labels = [
            {"rule_id": "A-C", "file_path": "a.c", "line": 1, "verdict": "TP"},
            {"rule_id": "B-C", "file_path": "a.c", "line": 2, "verdict": "FP"},
            {"rule_id": "B-C", "file_path": "a.c", "line": 9, "verdict": "TP"},
        ]
        table = {"A-C": {"default": "as_written", "strict": "as_written",
                         "pedantic": "as_written", "differs": False},
                 "B-C": {"default": "as_written", "strict": "not_enforced",
                         "pedantic": "not_enforced", "differs": True}}
        with mock.patch.object(db, "get_realworld_run", return_value={"id": 1}), \
                mock.patch.object(db, "get_realworld_results", return_value=[
                    {"tool": "sqc", "project": "p", "codebase_commit": "c"}]), \
                mock.patch.object(db, "_run_violation_keys", return_value=keys), \
                mock.patch.object(db, "get_ground_truth_labels", return_value=labels), \
                mock.patch.object(rule_presets, "load", return_value=table):
            return db.score_realworld_run(1, preset=preset)

    def test_without_a_preset_every_rule_is_scored_as_before(self):
        o = self._score(None)["overall"]
        self.assertNotIn("abstention", o)
        self.assertEqual((o["labeled_tp"], o["labeled_fp"]), (1, 1))
        self.assertEqual(o["tp_labels"], 2)
        self.assertEqual(o["run_findings"], 3)

    def test_a_declined_rule_leaves_every_denominator_and_is_counted(self):
        o = self._score("strict")["overall"]
        self.assertEqual((o["labeled_tp"], o["labeled_fp"]), (1, 0))
        self.assertEqual(o["precision_pct"], 100.0)
        self.assertEqual((o["tp_labels"], o["tp_detected"]), (1, 1))
        self.assertEqual(o["recall_pct"], 100.0)
        self.assertEqual(o["run_findings"], 1)
        a = o["abstention"]
        self.assertEqual(a["rules"], ["B-C"])
        self.assertEqual((a["findings"], a["labels"]), (2, 2))
        self.assertEqual(a["coverage_pct"], 33.3)

    def test_a_preset_that_declines_nothing_scores_everything(self):
        o = self._score("default")["overall"]
        self.assertEqual((o["labeled_tp"], o["labeled_fp"]), (1, 1))
        self.assertEqual(o["abstention"]["rules"], [])
        self.assertEqual(o["abstention"]["coverage_pct"], 100.0)
