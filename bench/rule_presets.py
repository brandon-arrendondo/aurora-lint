"""The per-rule x per-preset table, as bench reads it.

`rules_templates/rule-presets.json` is generated by build.rs from the
`[presets]` block of each rule's TOML (docs/rule-presets.rst renders the same
data). Bench stays free of Rust and of the crate: it reads that file.

A rule a preset declines (`not_enforced`) is an *abstention*: the preset
withholds a verdict on it, loudly, rather than guess. Scoring excludes an
abstained rule from the precision and recall denominators and reports how
much of the run that leaves enforced -- the coverage figure of selective
classification (ADR-0015). It is never a miss, and never a false positive.
"""
from __future__ import annotations

import json
from pathlib import Path

PRESETS = ("default", "strict", "pedantic")
TABLE_PATH = Path(__file__).resolve().parent.parent / "rules_templates" / "rule-presets.json"


def load(path: Path = TABLE_PATH) -> dict[str, dict]:
    """rule id -> {"default", "strict", "pedantic", "differs"}."""
    return json.loads(Path(path).read_text())["rules"]


def abstaining_rules(preset: str, table: dict[str, dict] | None = None) -> set[str]:
    """The rules `preset` declines."""
    if preset not in PRESETS:
        raise ValueError(f"unknown preset {preset!r}; one of {', '.join(PRESETS)}")
    table = load() if table is None else table
    return {rule for rule, cells in table.items() if cells[preset] == "not_enforced"}
